import { useQuery } from "react-query";
import api from "../api/axios";
import { useDispatch } from "react-redux";
import { showToast } from "../shared/AppSlice";

export function useEducations(toastTimer) {
  const dispatch = useDispatch();
  return useQuery({
    queryKey: ["fetch_educations"],
    queryFn: async () => {
      try {
        const response = await api.get("/api/accounts/educations/");
        const data = response.data;
        return data.results;
      } catch (error) {
        const errorMessage = error.message?.includes("Network Error")
          ? "خطا در اتصال به اینترنت"
          : "خطا در دریافت سوابق تحصیلی";
        dispatch(showToast(toastTimer, errorMessage, "error"));
        return [];
      }
    },
    refetchOnWindowFocus: false,
    refetchOnMount: false,
  });
}
